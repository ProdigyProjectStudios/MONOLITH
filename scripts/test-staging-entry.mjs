/** Verify a retained, loopback-only release with named staging identities. Read-only browser actions. */
import assert from "node:assert/strict";
import {readFile, writeFile} from "node:fs/promises";
import {chromium} from "playwright-core";
const origin=process.env.MONOLITH_STAGING_URL;
assert.ok(["127.0.0.1","localhost"].includes(new URL(origin).hostname));
const viewer=(await readFile(process.env.MONOLITH_VIEWER_TOKEN_FILE,"utf8")).trim();
const admin=(await readFile(process.env.MONOLITH_ADMIN_TOKEN_FILE,"utf8")).trim();
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || "/usr/bin/chromium",args:["--disable-dev-shm-usage","--no-proxy-server"]});
try {
 const ctx=await browser.newContext({viewport:{width:1440,height:920},reducedMotion:"reduce"});
 await ctx.addInitScript(()=>sessionStorage.setItem("monolith-api-origin",""));
 const p=await ctx.newPage();
 const routes=[],errors=[];
 p.on("request",r=>routes.push({origin:new URL(r.url()).origin,path:new URL(r.url()).pathname,method:r.method()}));
 p.on("pageerror",e=>errors.push(e.message));
 await p.goto(origin+"/#overview");
 assert.equal(await p.locator("html").getAttribute("data-runtime"),"production");
 await p.getByLabel("Workspace access token").fill(viewer);
 await p.getByRole("button",{name:"Connect",exact:true}).click();
 await p.getByRole("button",{name:/Refund approval delays/i}).first().waitFor();
 await p.reload();
 await p.getByRole("button",{name:/Refund approval delays/i}).first().waitFor();
 assert.ok(routes.some(r=>r.path==="/api/records"));
 assert.ok(routes.some(r=>r.path==="/api/report"));
 assert.ok(!routes.some(r=>r.path==="/demo.json" || r.path==="/runtime-worker.js"));
 assert.ok(!routes.some(r=>r.method==="POST"));
 await p.locator("aside.sidebar").getByRole("button",{name:"Data sources",exact:true}).click();
 await p.getByRole("button",{name:"Sign out"}).waitFor();
 assert.equal(await p.getByRole("button",{name:"Use browser workspace"}).count(),0);
 assert.equal(await p.getByRole("button",{name:"Connect API",exact:true}).count(),0);
 await p.getByRole("button",{name:"Sign out"}).click();
 await p.getByLabel("Workspace access token").waitFor();
 await p.getByLabel("Workspace access token").fill(admin);
 await p.getByRole("button",{name:"Connect",exact:true}).click();
 await p.getByRole("heading",{name:"Runtime readiness",exact:true}).waitFor();
 await p.getByText("Redis online",{exact:true}).waitFor();
 assert.deepEqual(errors,[]);
 const headers={Authorization:"Bearer "+admin};
 const readiness=await(await fetch(origin+"/api/runtime/readiness",{headers})).json();
 assert.equal(readiness.provider.calls_enabled,false);
 const health=await(await fetch(origin+"/api/health/ready")).json();assert.equal(health.status,"ready");
 const metrics=await(await fetch(origin+"/api/operations/metrics",{headers})).json();
 assert.equal(metrics.database.dialect,"postgresql");assert.ok(metrics.database.records.events>=1706);
 assert.ok(metrics.worker.active>=1);assert.equal(metrics.queue.status,"reachable");
 assert.equal((await fetch(origin+"/api/operations/metrics",{headers:{Authorization:"Bearer "+viewer}})).status,403);
 const result={status:"PASSED",host_scope:"workspace staging loopback",production_profile:true,credential_role_switch:true,viewer_reload:true,source_mode:"paginated authenticated API",browser_demo_requests:0,third_party_requests:routes.filter(r=>r.origin!==origin && /^http/.test(r.origin)).length,worker_count:metrics.worker.active,database:metrics.database.dialect,seed_event_count:metrics.database.records.events,model_calls_enabled:readiness.provider.calls_enabled,page_errors:errors};
 assert.equal(result.third_party_requests,0);
 if(process.env.MONOLITH_STAGING_EVIDENCE)await writeFile(process.env.MONOLITH_STAGING_EVIDENCE,JSON.stringify(result,null,2)+"\n");
 console.log("Same-origin Chromium staging passed · viewer sign-in and reload, paginated server evidence, role switch, PostgreSQL/Redis/RQ and disabled provider execution.");
} finally {await browser.close();}
